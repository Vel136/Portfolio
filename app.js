// ══ Scroll Reveal ════════════════════════════════════════════════════════
class ScrollReveal {
  constructor() {
    this._observer = new IntersectionObserver(
      (entries) => {
        entries.forEach(entry => {
          if (entry.isIntersecting) {
            entry.target.classList.add('visible');
            this._observer.unobserve(entry.target);
          }
        });
      },
      { threshold: 0.06, rootMargin: '0px 0px -30px 0px' }
    );
  }

  observe() {
    document.querySelectorAll('.reveal').forEach(el => this._observer.observe(el));
  }

  refresh() {
    document.querySelectorAll('.reveal:not([data-observed])').forEach(el => {
      el.dataset.observed = '1';
      this._observer.observe(el);
    });
  }
}

// ══ App ══════════════════════════════════════════════════════════════════
class App {
  constructor() {
    this._root = document.getElementById('app');
    this._reveal = new ScrollReveal();
  }

  init() {
    this._renderSidebar();
    this._renderMain();
    this._reveal.observe();
  }

  _renderSidebar() {
    const sidebar = new Sidebar(SiteConfig.brand, SiteConfig.navigation);
    sidebar.render(this._root);
  }

  _renderMain() {
    const main = document.createElement('div');
    main.className = 'main-content';
    this._root.appendChild(main);

    const sections = [
      new PastWorks(SiteConfig.works),
      new Libraries(SiteConfig.libraries),
      new Pricing(SiteConfig.pricing),
      new Achievements(SiteConfig.achievements),
      new Skills(SiteConfig.skills),
      new Tos(SiteConfig.tos),
      new Contact(SiteConfig.contact),
    ];

    sections.forEach(component => component.render(main));

    requestAnimationFrame(() => this._reveal.refresh());
  }
}

// ══ Bootstrap ════════════════════════════════════════════════════════════
document.addEventListener('DOMContentLoaded', () => {
  const app = new App();
  app.init();
});
